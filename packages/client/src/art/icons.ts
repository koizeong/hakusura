function shade(color: number, t: number): string {
  const ch = [(color >> 16) & 255, (color >> 8) & 255, color & 255].map((c) => Math.round(t > 0 ? c + (255 - c) * t : c * (1 + t)));
  return `#${ch.map((c) => c.toString(16).padStart(2, '0')).join('')}`;
}

/** 状態の印の絵。縁取りまで含めて 11×11 升 */
export function drawStatusIcon(id: StatusId): PixelGrid {
  const g = new PixelGrid(STATUS_ICON_SIZE + 2, STATUS_ICON_SIZE + 2);
  const color = (STATUSES[id] as { color: number }).color;
  const palette: Record<string, string> = { '#': shade(color, 0.05), '+': shade(color, 0.55), '-': shade(color, -0.5), w: '#f2ead8' };
  const rows = ICONS[id];
  if (!rows) {
    g.ellipse(5, 5, 3.5, 3.5, palette['#']!);
    g.set(4, 4, palette['+']!);
  } else {
    rows.forEach((row, y) => [...row].forEach((ch, x) => palette[ch] && g.set(x + 1, y + 1, palette[ch]!)));
  }
  g.outline('#120d0b');
  return g;
}

const urls = new Map<StatusId, string>();

/** 画面の HTML に置くための、状態の印の画像(data URL)。作ったものは使い回す */
export function statusIconUrl(id: StatusId): string {
  let url = urls.get(id);
  if (url) return url;
  const g = drawStatusIcon(id);
  const canvas = document.createElement('canvas');
  canvas.width = g.width;
  canvas.height = g.height;
  g.paint(canvas.getContext('2d')!, 0, 0);
  url = canvas.toDataURL();
  urls.set(id, url);
  return url;
}
